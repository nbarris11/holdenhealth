export type ChallengePageCopy = Record<(typeof challengePageFields)[number]["key"], string>;

export function normalizeChallengePageCopy(value: unknown): ChallengePageCopy {
  const record = value && typeof value === "object" && !Array.isArray(value)
    ? value as Record<string, unknown> : {};
  return Object.fromEntries(challengePageFields.map((field) => {
    const text = record[field.key];
    return [field.key, typeof text === "string" && text.trim() && text.length <= field.maxLength ? text : field.default];
  })) as ChallengePageCopy;
}

export function parseChallengePageCopy(data: FormData): { value: ChallengePageCopy; error?: never } | { error: string; value?: never } {
  const value = {} as ChallengePageCopy;
  for (const field of challengePageFields) {
    const text = data.get(field.key);
    if (typeof text !== "string" || !text.trim() || text.trim().length > field.maxLength) {
      return { error: `Enter ${field.label.toLowerCase()} (${field.maxLength} characters maximum).` };
    }
    value[field.key] = text.trim();
  }
  return { value };
}
